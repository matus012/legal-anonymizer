# -------------------------------------------------------------------------- token helpers
# A gazetteer token must look like a Slovak proper noun: an initial capital, at least one
# lowercase letter after it, and at least three characters. Measured on the demo contract,
# without these three conditions the register matched:
#   "VIN 1HGBH41JXMN109186"  -> ULICA "VIN"      (an ALL-CAPS abbreviation, and the register
#                                                 really does contain a street "Vin")
#   "Článok I" / "Článok II" -> KATASTER "I"/"II" (Roman numerals; the register contains
#                                                 one- and two-letter place names)
# None of these is a place in context, and all three are things a legal document contains on
# every page. The rule is the same shape as the single-character guard in
# detect/known_entities.py and exists for the same reason: a needle short or generic enough to
# match everywhere is not evidence, it is noise, and noise in the review list is what makes a
# reviewer start blind-approving (context.md 9).
_MIN_GAZETTEER_TOKEN = 3

# CASE (round-2 red-team, R2-5/C-5): the Amendment-6 guard above needs a lowercase letter to
# exist AT ALL, which an all_caps/lowercase mutation removes from the entire unit -- the
# guard then rejects every place/street/name token regardless of whether it is a real
# gazetteer hit, punishing the STEM INDEX lookup (which still matches: stem("KOSICE") ==
# stem("Kosice")) for a precision guard that has no evidence left to test. Relaxed to "looks
# like a whole word, no digits" ONLY when `document_is_single_case` (detect/identifiers.py,
# shared across every module that needs this gate) says the unit itself has no
# capitalisation signal left to lose -- an ordinary mixed-case paragraph never reaches it.
# This does not re-admit "VIN" (redteam finding C-5): that unit is short (~11 letters between
# the label and the code), under the shared helper's length floor, so it still gets the
# STRICT guard even when it happens to be written in a single case. Unlike name_anchors.py
# and orgs.py, no right-boundary fix is needed here: `_capitalized` gates a single TOKEN
# (never a multi-token greedy run), so there is nothing for a relaxed match to swallow.
def _capitalized(core: str, *, relaxed: bool = False) -> bool:
    if len(core) < _MIN_GAZETTEER_TOKEN:
        return False
    if relaxed:
        return core.isalpha()
    return core[:1].isupper() and any(ch.islower() for ch in core[1:])


def _adjacent(text: str, end: int, next_start: int) -> bool:
    """True when nothing but whitespace separates two tokens. Punctuation between them (a
    full stop, a comma) means they are not one name — ``"… bol Ján. Zmluva …"`` must not
    become ``Ján. Zmluva``."""
    return text[end:next_start].strip() == ""


# ---------------------------------------------------------------------------- place walk
def _match_multi(
    text: str,
    toks: list[tuple[str, int, int]],
    tstems: list[str],
    i: int,
    entries: tuple[tuple[tuple[str, ...], str], ...],
) -> int | None:
    """Index of the LAST token of the longest multi-word entry starting at token ``i``."""
    for stems, _canonical in entries:
        n = len(stems)
        if i + n > len(toks):
            continue
        if any(tstems[i + k] != stems[k] for k in range(n)):
            continue
        if any(not _adjacent(text, toks[i + k][2], toks[i + k + 1][1]) for k in range(n - 1)):
            continue
        return i + n - 1
    return None


def _match_multi_folded(
    text: str,
    toks: list[tuple[str, int, int]],
    tstems: list[str],
    tstems_ascii: list[str],
    i: int,
    s: str,
    s_ascii: str,
    multi: dict[str, tuple],
    multi_ascii: dict[str, tuple],
) -> int | None:
    """``_match_multi``, tried first on the exact (diacritic-preserving) stem and, only if
    that misses, again on the diacritic-folded stem against the folded index (R2-2). Offset-
    safe: both attempts return a token INDEX, and every span the caller builds from it still
    comes from ``toks`` -- the original token positions, never a folded string."""
    if s in multi:
        last = _match_multi(text, toks, tstems, i, multi[s])
        if last is not None:
            return last
    if s_ascii in multi_ascii:
        return _match_multi(text, toks, tstems_ascii, i, multi_ascii[s_ascii])
    return None


def _place_hits(
    text: str,
    toks: list[tuple[str, int, int]],
    tstems: list[str],
    tstems_ascii: list[str],
    filename: str,
    type_: str,
    *,
    relaxed: bool,
) -> list[Candidate]:
    single, multi, head = _index(filename)
    single_a, multi_a, head_a = _index_ascii(filename)
    out: list[Candidate] = []
    i = 0
    while i < len(toks):
        core, start, end = toks[i]
        if not _capitalized(core, relaxed=relaxed):
            i += 1
            continue
        s, s_a = tstems[i], tstems_ascii[i]
        last = _match_multi_folded(text, toks, tstems, tstems_ascii, i, s, s_a, multi, multi_a)
        if last is not None:
            out.append(_place_candidate(text, type_, start, toks[last][2]))
            i = last + 1
            continue
        if s in single or s_a in single_a:
            out.append(_place_candidate(text, type_, start, end))
        elif s in head or s_a in head_a:
            # head-noun-only hit on a multi-word place — the recorded sub-gap, review bucket
            out.append(Candidate(type_, text[start:end], start, end, False, "n/a"))
        i += 1
    return out


def _place_candidate(text: str, type_: str, start: int, end: int) -> Candidate:
    surface = text[start:end]
    auto = True
    if " " not in surface and stem(surface) in _stoplist_stems():
        auto = _place_anchored(text, start, end)
    return Candidate(type_, surface, start, end, auto, "n/a")


# --------------------------------------------------------------------------- street walk
# --------------------------------------------------------------------- ULICA declension
# Slovak adjectival endings, by the nominative ending of the head word. Streets are adjectives
# far more often than nouns -- Hlavná, Krátka, Školská, Dlhý, Štúrova -- and an address puts
# them in the locative or genitive: "na Hlavnej ulici", "z Krátkej", "na Štúrovej".
#
# GENERATED, not stripped. detect/declension.py's suffix inventory excludes the plain
# adjectival -ej on purpose: that exclusion is the discriminator between a possessive form of
# a SURNAME ("Kovacovej", which IS the person) and an adjective derived from it ("Kovacskej",
# which is not). Widening the shared stemmer for streets would break names, so instead the
# street index gains the inflected forms and the stemmer is left exactly as it was.
_ADJ_FORMS = {
    # Feminine, BOTH endings. Slovak rhythmic shortening shortens the adjective ending after a
    # long stem syllable -- "hlavná" keeps -á, "krátka" shortens to -a -- and on the register
    # the short form is the MAJORITY: 4 708 head words end in -a against 2 324 in -á.
    "a": ("ej", "u", "ou", "e", "ych", "ymi"),      # feminine short: Krátka -> Krátkej ...
    "á": ("ej", "ú", "ou", "e", "ych", "ymi"),      # feminine long:  Hlavná -> Hlavnej ...
    "ý": ("eho", "emu", "om", "ym", "e", "ych"),    # masculine: Dlhý -> Dlhého / Dlhom ...
    "é": ("eho", "emu", "om", "ym"),                # neuter:   Dlhé -> Dlhého ...
}
# Possessive streets (Štúrova, Hviezdoslavova, Kollárova) end in -ova/-ina and decline like a
# feminine adjective. Restricted to those two suffixes: a street that is a NOUN ending in -a
# ("Lipa") declines differently, and generating adjectival forms for it would index words that
# are not the street.
_POSSESSIVE_SUFFIXES = ("ova", "ina")
_POSSESSIVE_FORMS = ("ovej", "ovu", "ovou", "inej", "inu", "inou")


def _declined_variants(name: str) -> list[str]:
    """Every inflected spelling of ``name``'s head word. Nominative is NOT included -- it is
    already indexed by the ordinary path."""
    head = name.split()[-1] if name.split() else name
    if len(head) < 4:
        return []
    lowered = head.lower()
    out: list[str] = []
    for suffix in _POSSESSIVE_SUFFIXES:
        if lowered.endswith(suffix):
            base = head[: -len(suffix)]
            out.extend(base + form for form in _POSSESSIVE_FORMS
                       if form.startswith(suffix[:2]))
            break
    else:
        endings = _ADJ_FORMS.get(head[-1])
        if endings:
            out.extend(head[:-1] + ending for ending in endings)
    prefix = name[: len(name) - len(head)]
    return [prefix + variant for variant in out]


@functools.lru_cache(maxsize=None)
def _street_declined_index() -> tuple[dict[str, str], dict[str, str]]:
    """(stem -> canonical, ascii-stem -> canonical) for the DECLINED forms of every street.

    Single-head-word entries only. A multi-word register entry ("Ulica Štúrova") already
    matches through the multi-word path on its own tokens, and its head word is covered here.
    """
    by_stem: dict[str, str] = {}
    by_stem_ascii: dict[str, str] = {}
    for name in _load_names(_ULICE):
        for variant in _declined_variants(name):
            words = variant.split()
            if not words:
                continue
            head = words[-1]
            by_stem.setdefault(stem(head), name)
            by_stem_ascii.setdefault(stem(ascii_fold(head)), name)
    return by_stem, by_stem_ascii


def _street_hits(
    text: str,
    toks: list[tuple[str, int, int]],
    tstems: list[str],
    tstems_ascii: list[str],
    *,
    relaxed: bool,
) -> list[Candidate]:
    single, multi, _head = _index(_ULICE)
    single_a, multi_a, _head_a = _index_ascii(_ULICE)
    out: list[Candidate] = []
    i = 0
    while i < len(toks):
        core, start, end = toks[i]
        if not _capitalized(core, relaxed=relaxed):
            i += 1
            continue
        s, s_a = tstems[i], tstems_ascii[i]
        last = _match_multi_folded(text, toks, tstems, tstems_ascii, i, s, s_a, multi, multi_a)
        if last is not None:
            span_end = toks[last][2]
            if _street_anchored(text, start, span_end):
                out.append(Candidate("ULICA", text[start:span_end], start, span_end, True, "n/a"))
                i = last + 1
                continue
            # The longer entry exists in the register ("Ulica Štúrova") but nothing anchors
            # it here, so it is dropped — and the walk does NOT skip its tokens: the inner
            # name may still be anchored on its own ("bydlisko Ulica Štúrova" anchors
            # "Štúrova" on the keyword "Ulica").
        declined, declined_a = _street_declined_index()
        if s in single or s_a in single_a or s in declined or s_a in declined_a:
            stoplisted = s in _stoplist_stems() or s_a in _stoplist_stems_ascii()
            if _street_anchored(text, start, end, stoplisted=stoplisted):
                out.append(Candidate("ULICA", text[start:end], start, end, True, "n/a"))
        i += 1
    return out


# ----------------------------------------------------------------------------- name walk
def _name_hits(
    text: str,
    toks: list[tuple[str, int, int]],
    tstems: list[str],
    tstems_ascii: list[str],
    *,
    relaxed: bool,
) -> list[Candidate]:
    given, _given_m, _given_h = _index(_FIRST_NAMES)
    given_a = _index_ascii(_FIRST_NAMES)[0]
    surnames = _index(_SURNAMES)[0]
    surnames_a = _index_ascii(_SURNAMES)[0]
    stopped = _surname_stop_stems()
    stopped_a = _surname_stop_stems_ascii()
    out: list[Candidate] = []
    i = 0
    while i < len(toks):
        core, start, end = toks[i]
        if not _capitalized(core, relaxed=relaxed):
            i += 1
            continue
        s, s_a = tstems[i], tstems_ascii[i]
        if s in given or s_a in given_a:
            nxt = toks[i + 1] if i + 1 < len(toks) else None
            if nxt is not None and _capitalized(nxt[0], relaxed=relaxed) and _adjacent(text, end, nxt[1]):
                out.append(Candidate("MENO", text[start : nxt[2]], start, nxt[2], True, "n/a"))
                i += 2
                continue
            out.append(Candidate("MENO", core, start, end, False, "n/a"))
        elif (s in surnames or s_a in surnames_a) and s not in stopped and s_a not in stopped_a:
            out.append(Candidate("MENO", core, start, end, False, "n/a"))
        i += 1
    return out


# --------------------------------------------------------------------------- entry point
def detect_gazetteer(text: str, config: DetectConfig) -> list[Candidate]:
    """Detect OBEC, KATASTER, ULICA and gazetteer MENO spans (contract §8).

    ``config`` carries no toggle relevant to this module (both DetectConfig fields govern
    checksum tagging and DATUM redaction); it is accepted to match the frozen per-module
    signature so the orchestrator's dispatch stays uniform.
    """
    del config
    toks = list(_tokens(text))
    if not toks:
        return []
    tstems = [stem(core) for core, _s, _e in toks]
    tstems_ascii = [ascii_fold(s) for s in tstems]
    relaxed = document_is_single_case(text)
    out: list[Candidate] = []
    out.extend(_place_hits(text, toks, tstems, tstems_ascii, _OBCE, "OBEC", relaxed=relaxed))
    out.extend(
        _place_hits(text, toks, tstems, tstems_ascii, _KATASTER, "KATASTER", relaxed=relaxed)
    )
    out.extend(_street_hits(text, toks, tstems, tstems_ascii, relaxed=relaxed))
    out.extend(_name_hits(text, toks, tstems, tstems_ascii, relaxed=relaxed))
    return out
