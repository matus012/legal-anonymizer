"""v1.1 detection engine, layer 2 (CONTRACTS_v11.md §8/§12, C3 round): the GAZETTEER —
OBEC, KATASTER, ULICA and gazetteer-driven MENO. Text-in, spans-out. No file I/O beyond
the bundled read-only data files, no docx/pdf, no ground truth, no import of corpus/ or
eval/.

context.md §4.2: the lists are finite, public and shipped with the app (LICENSES.md records
every source and licence). They are a RECALL AID, not an authority — a place or name absent
from them is still reachable through the anchor detectors and the user's known-entity list.

The data files are read-only inputs built by ``tools/build_gazetteer.py``; this module never
writes them and never regenerates them.

DECLENSION (context.md §5, the whole point of this module)
----------------------------------------------------------
``Košice`` must match ``Košiciach`` / ``Košíc`` / ``Košiciam``; ``Michalovce`` must match
``Michalovciach`` / ``Michaloviec``. Matching is therefore by STEM, computed by
``detect.declension.stem`` — the project's single Slovak stemmer. This module does not
reimplement stemming, does not widen the suffix inventory, and does not tokenize by hand: it
reuses ``detect.declension._tokens`` so token boundaries and offsets are identical to the
ones the stemmer was written against. (Underscore-private, deliberately: a second tokenizer
that drifted from the stemmer's edge-punctuation handling would silently shift spans, and the
writers slice the output document by offsets.)

THE DISCRIMINATOR is untouched and is exercised through the surname index: ``stem("Kováčovej")
== stem("Kováč")`` so a possessive declension of a name matches, while ``stem("Kováčskej")``
keeps the ``-sk-`` derivational infix and therefore does not. Nothing here adds adjectival
endings to the stemmer.

Each stem index is built ONCE per data file and cached; 12 000 street names are parsed on
first use, never at import time and never again per page.

KNOWN SUB-GAP (recorded in handoff.md, NOT fixed here)
-----------------------------------------------------
A multi-word place with an ADJECTIVAL modifier only matches its head noun in oblique cases:
``Banská Bystrica`` → ``Banskej Bystrici`` stems to (``banskej``, ``bystric``) and the
modifier's stem does not meet the nominative's, because ``-ej`` is an adjectival ending and is
deliberately absent from the stemmer's closed inventory. Fixing it by adding adjectival
endings would destroy the discriminator, so it is NOT fixed. Instead every multi-word entry is
ALSO indexed by its head noun, and a head-noun-only hit is emitted into the REVIEW bucket
(``auto=False``): the reviewer still sees ``Bystrici``, but a bare head noun (``Ves``,
``Streda``) is too weak to auto-redact on its own.

BUCKETING (contract §4 type names; §12 for ULICA)
-------------------------------------------------
* ``OBEC`` (obce.json), ``KATASTER`` (katastralne_uzemia.json) — ``auto=True``.
* ``ULICA`` (ulice.json) — ``auto=True`` ONLY when the street name is followed by a house
  number or preceded by ``ul.`` / ``ulica`` / ``nám.`` / ``námestie`` / ``trieda`` / ``cesta``
  (case-insensitive). **A bare street name is not emitted at all.** Many Slovak streets are
  named after ordinary nouns, and 12 000 of them matched unanchored would flood a document;
  contract §12 (ADDENDUM 1 R3) states the restriction as "matched ONLY when …", so an
  unanchored street is dropped rather than demoted.
* ``MENO`` — a surname alone is ``auto=False`` (too weak a signal to auto-redact); a given
  name immediately followed by a Capitalized token is the full personal name and is
  ``auto=True`` over BOTH tokens; a given name alone is ``auto=False``.

STOPLISTS
---------
``stoplist.json`` holds place/street names that are also ordinary Slovak words or legal
vocabulary (``Hora``, ``Lipa``, ``Most``, ``Článok``, ``Zmluva``, ``Súd``). A hit on one of
those never reaches the AUTO bucket on the strength of the word alone — it is DEMOTED to
``auto=False``, not dropped, so the reviewer keeps the chance to tick it. It IS auto when an
independent anchor confirms it: an address/place keyword within 25 characters before, or a
house number / PSČ immediately after. The stoplist is applied to single-token surfaces only —
``Nová`` is stoplisted, but ``Spišská Nová Ves`` is unambiguous and must stay auto.

``_SURNAME_COMMON_WORDS`` below is the surname-specific stoplist the sprint brief asks for
(``Hora``, ``Vlk``, ``Kráľ``, ``Sladký``, …). It lives here as a module constant rather than in
``stoplist.json`` for two reasons: the data file is machine-generated by
``tools/build_gazetteer.py`` and is about PLACE names (adding hand-written surname entries to
it would be silently discarded by the next regeneration), and its effect is different — a
surname hit is already ``auto=False``, so demotion would be a no-op; these entries are
SUPPRESSED entirely, because a review-bucket candidate on every capitalised ``Kráľ`` or
``Malý`` in running prose is noise that makes the review list unusable. Nothing is lost when
the word really is a surname: the given-name + Capitalized-token rule still emits the full
name with ``auto=True``.

This module never resolves overlaps against other detector modules, and emits both an OBEC
and a KATASTER candidate where the two registers share a name — that is by design; contract
§5's resolver in ``detect/core.py`` settles every cross-type collision.
"""
