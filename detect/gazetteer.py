def _data_dir() -> str:
    """The bundled data directory: under ``sys._MEIPASS`` in a frozen build (anonymizer.spec
    ships the JSONs to ``detect/gazetteer_data`` there), next to this package otherwise."""
    if getattr(sys, "frozen", False):
        return os.path.join(getattr(sys, "_MEIPASS", ""), "detect", "gazetteer_data")
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "gazetteer_data")


@functools.lru_cache(maxsize=None)
def _load_names(filename: str) -> tuple[str, ...]:
    path = os.path.join(_data_dir(), filename)
    try:
        with open(path, encoding="utf-8") as fh:
            raw = json.load(fh)
    except OSError as exc:
        raise GazetteerDataError(f"gazetteer data file missing or unreadable: {path}") from exc
    except (json.JSONDecodeError, UnicodeDecodeError) as exc:
        raise GazetteerDataError(f"gazetteer data file is corrupt: {path} ({exc})") from exc
    if not isinstance(raw, list) or not all(isinstance(x, str) for x in raw):
        raise GazetteerDataError(
            f"gazetteer data file has the wrong shape (expected a JSON array of strings): {path}"
        )
    return tuple(raw)


@functools.lru_cache(maxsize=None)
def _index(filename: str) -> tuple[dict[str, str], dict[str, tuple], dict[str, str]]:
    """(single, multi, head) stem indices for one data file. Built once, cached forever.

    ``single``: stem -> canonical, for one-word entries.
    ``multi``:  first-word stem -> tuple of (word stems, canonical), longest entry first.
    ``head``:   head-noun stem -> canonical, for multi-word entries. The head noun is the last
                word of the LEADING run of capitalised words, so ``Nová Ves nad Žitavou`` heads
                on ``Ves`` and not on ``Žitavou``.
    """
    single: dict[str, str] = {}
    multi: dict[str, list[tuple[tuple[str, ...], str]]] = {}
    head: dict[str, str] = {}
    for name in _load_names(filename):
        words = name.split()
        if not words:
            continue
        stems = tuple(stem(w) for w in words)
        if len(words) == 1:
            single.setdefault(stems[0], name)
            continue
        multi.setdefault(stems[0], []).append((stems, name))
        run = 0
        while run + 1 < len(words) and words[run + 1][:1].isupper():
            run += 1
        head.setdefault(stems[run], name)
    frozen_multi = {
        key: tuple(sorted(vals, key=lambda sv: len(sv[0]), reverse=True))
        for key, vals in multi.items()
    }
    return single, frozen_multi, head


@functools.lru_cache(maxsize=None)
def _index_ascii(filename: str) -> tuple[dict[str, str], dict[str, tuple], dict[str, str]]:
    """A DIACRITIC-FOLDED mirror of ``_index`` (round-2 red-team, R2-2): "Kosice" (no
    diacritics -- a mutated document, or a lawyer who never learned to type them) must still
    meet ``Košice``'s stem, and the plain stem index is diacritic-EXACT because ``stem()``
    deliberately preserves them (the -sk-/-ck- discriminator is a consonant infix, untouched
    by folding vowels and consonant diacritics away).

    OFFSET-SAFE even though ``ascii_fold`` is not 1:1: the fold is applied only to the
    DICTIONARY KEY, never to the text a span is cut from. Every canonical value and every
    offset returned to a caller still comes from ``_index``'s own (unfolded) data and from
    the caller's own token span -- this function only widens which KEY reaches that unchanged
    data, exactly the way ``diacritic_pattern`` widens a regex pattern instead of folding the
    text it matches against."""
    single, multi, head = _index(filename)
    single_a: dict[str, str] = {ascii_fold(k): v for k, v in single.items()}
    multi_a: dict[str, list[tuple[tuple[str, ...], str]]] = {}
    for k, entries in multi.items():
        multi_a.setdefault(ascii_fold(k), []).extend(entries)
    head_a: dict[str, str] = {ascii_fold(k): v for k, v in head.items()}
    return single_a, {k: tuple(v) for k, v in multi_a.items()}, head_a


@functools.lru_cache(maxsize=None)
def _stoplist_stems() -> frozenset[str]:
    return frozenset(stem(w) for w in _load_names(_STOPLIST))


@functools.lru_cache(maxsize=None)
def _stoplist_stems_ascii() -> frozenset[str]:
    return frozenset(ascii_fold(s) for s in _stoplist_stems())


def _clear_caches() -> None:
    """Drop every cached index. Exists for the data-loading tests, which repoint
    ``_data_dir`` at a temporary directory."""
    _load_names.cache_clear()
    _index.cache_clear()
    _index_ascii.cache_clear()
    _stoplist_stems.cache_clear()
    _stoplist_stems_ascii.cache_clear()


# ----------------------------------------------------------------------------- anchors
# Place/address context that independently confirms a stoplisted word really is a place.
# CASE / DIACRITICS: both anchor tests below are context-WINDOW checks (never sliced, never
# a source of an offset), so they use technique B -- fold the window with ``ascii_fold`` and
# match against an ascii-spelled, lowercase pattern. That one fold covers case AND
# diacritics together, so no separate ``re.IGNORECASE`` is needed here.
_PLACE_ANCHOR_RE = re.compile(
    r"ul\.|ulica|ulici|nam\.|namest|trieda|cesta|obec|obci|obce|mesto|meste|mesta"
    r"|okres|kataster|katastralne uzemie|k\.\s?u\.|trvale bytom|bytom|bydlisko"
    r"|so sidlom|sidlo|na adrese|adresa|adrese|pobyt"
)
# Street-specific keyword, immediately before the street name (contract §12).
# _SEP_ANCHOR (line_break_mid, break-BETWEEN-words case): widened locally to `\s` for
# this ONE gap -- the keyword-to-street-name separator -- rather than by touching the
# module's shared `_SEP`, which also feeds `_NUMBER_AFTER_RE`/`_HOUSENUM_AFTER_RE`/
# `_PSC_AFTER_RE` (the number/PSC-after-the-name anchors for OBEC/KATASTER/ULICA, out of
# scope here). A PDF wrap after "ul." or "nám." is routine and killed the whole keyword
# anchor at the old horizontal-only separator; this gap is bounded by the `$` anchor
# against a fixed-length trailing window, never a terminator for a free-running value,
# so widening it cannot let anything swallow past where the street name starts.
_SEP_ANCHOR = r"\s"
_STREET_KEYWORD_RE = re.compile(rf"(?:ul\.|ulica|nam\.|namestie|trieda|cesta){_SEP_ANCHOR}+$")
# A house number (optionally with an orientation suffix) or a PSČ right after the name.
_NUMBER_AFTER_RE = re.compile(
    rf"^,?{_SEP}*(?:\d{{3}}{_SEP}\d{{2}}|\d{{1,4}}(?:/[A-Za-z0-9]{{1,3}})?)(?!\d)"
)
_HOUSENUM_AFTER_RE = re.compile(rf"^{_SEP}+\d{{1,4}}(?:/[A-Za-z0-9]{{1,3}})?(?!\d)")
# A PSC specifically (spaced or contiguous five digits). Unlike a bare house number this is
# unambiguous address context even after an ordinary-word place name.
_PSC_AFTER_RE = re.compile(rf"^,?{_SEP}*(?:\d{{3}}{_SEP}\d{{2}}|\d{{5}})(?!\d)")

# The same keywords INFLECTED and FOLLOWING the name: "na Hlavnej ULICI", "na Štúrovom
# NÁMESTÍ". Matched on the ascii-folded text, so the accents in "námestí" need no alternatives.
# Bounded by a fixed window and anchored at the start of the text AFTER the name, so it cannot
# reach past the words immediately following it.
_STREET_KEYWORD_AFTER_RE = re.compile(
    rf"^{_SEP_ANCHOR}+(?:ulic[aeiuoy]|namest[ie][a-z]?|tried[aeuoy]|cest[aeuoy])\b"
)

_ANCHOR_WINDOW = 25


def _place_anchored(text: str, start: int, end: int) -> bool:
    """Confirmation that a STOPLISTED word really is a place here.

    Only a place/address KEYWORD counts. The "number immediately after" signal was tried and
    removed: it fires on "Strana 3 z 12" (an ordinary page footer — "Strana" is both a real
    municipality name and the Slovak word for page/party), on "Clanok 5" and on "Priloha 2".
    A bare number after an ordinary word carries no address meaning, so as a confirmation
    signal for a word we have ALREADY flagged as ambiguous it is worthless — it re-admits
    exactly the collisions the stoplist exists to catch.

    A PSC is different and still counts: "Lipa 040 01" is unambiguous address context, because
    a five-digit postal code is not a page number or an article number. So the distinction is
    PSC yes, bare 1-4 digit house number no.

    A plain house number still anchors a NON-stoplisted street (see _street_anchored); this
    stricter rule applies only to the 79 hand-listed collision words."""
    return bool(
        _PLACE_ANCHOR_RE.search(ascii_fold(text[max(0, start - _ANCHOR_WINDOW) : start]))
        or _PSC_AFTER_RE.match(text[end:])
    )


def _street_anchored(text: str, start: int, end: int, *, stoplisted: bool = False) -> bool:
    """Is this token anchored strongly enough to call it a street?

    Normally either signal will do: an explicit street KEYWORD before it, or a house NUMBER
    after it. For a STOPLISTED word the trailing number is not good enough, and the corpus
    says why: "Strana" is a real street name in the Register adries and also the Slovak word
    for "page"/"party", so "Strana 3 z 12" — an ordinary page footer — matched the
    number-after rule and was auto-redacted as an address. "Článok 5" and "Príloha 2" are the
    same shape. A number after an ordinary word carries no address meaning whatsoever.

    So a stoplisted word must be confirmed by the street KEYWORD specifically. This is the one
    place in the gazetteer where precision beats recall, and it is narrow on purpose: it
    applies only to the 79 hand-listed collision words, and only to the weaker of the two
    anchors. "ul. Strana 3" still matches."""
    keyword = _STREET_KEYWORD_RE.search(ascii_fold(text[max(0, start - _ANCHOR_WINDOW) : start]))
    # ... or an INFLECTED keyword AFTER the name. "na Hlavnej ulici" is how an address reads
    # when the street name is declined, and it puts the keyword on the other side and in the
    # locative ("ulici", not "ulica"). Looking only backwards made the declined form
    # unreachable -- the two halves of this only work together.
    if not keyword:
        keyword = _STREET_KEYWORD_AFTER_RE.match(ascii_fold(text[end : end + _ANCHOR_WINDOW]))
    if stoplisted:
        return bool(keyword)
    return bool(keyword or _HOUSENUM_AFTER_RE.match(text[end:]))


