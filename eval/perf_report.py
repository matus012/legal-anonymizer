"""Perf report — Phase E gate 3, REPORT ONLY, NO THRESHOLD (CONTRACTS_v11.md).

    python -m eval.perf_report

Wall time per page and peak memory for redacting one LARGE DOCX (~300 paragraph-pages) and
one LARGE PDF. Both large inputs are GENERATED by this module into the session scratchpad
directory (never the repo, never committed — see ``_SCRATCH`` below) and deleted at the end
of the run.

**TRANSIENT FINDING, since resolved — recorded because it recurs.** Mid-session, while
``detect/core.py``/``writer/pdf_body.py`` were being actively rewritten by concurrent agents
(the dual-normalized-view merge, ``detect/normalize.py``), ``redact_pdf()`` on THIS module's
own generated content briefly took **75s for 2 pages** and **297s for 5 pages** — worse than
linear — against a real corpus PDF's 0.52s. Re-measured after those agents' commits landed
(``d063cfe``, ``0baa182``, ``ed6fee8``): 2 pages = 1.2s, 50 pages = 13.7s (~0.27s/page,
linear). The number was real at the moment it was taken; it described an in-progress edit,
not the shipped code, and is kept here as a reminder that a perf numbers ever taken against a
mid-edit tree must be re-measured before being reported, never assumed stale-but-safe.

**Memory instrument**: ``psutil`` is not installed in this project's venv (checked directly:
``import psutil`` raises ``ModuleNotFoundError``; it is not in ``requirements.txt``). Adding a
new dependency is out of scope for an ``eval/``-only round, so this module uses
``tracemalloc`` (stdlib, always available) instead. **That is NOT the same number as process
RSS** — it is peak PYTHON-HEAP allocation only, and it misses memory the redaction path pushes
into native extensions (``lxml``, ``python-docx``'s zip writer, PyMuPDF/``fitz``, both of which
do real work in C). It is reported honestly under that name, never relabelled as RSS.

**"Page" for DOCX**: a ``.docx`` has no fixed page count — it reflows to whatever opens it.
"Paragraph-pages" here means paragraphs; ``time / paragraph`` is the real, unambiguous number.
A "per rendered page" figure is ALSO printed, using a documented, approximate density (40
paragraphs / page, this module's own generated paragraphs are short single-line PII
sentences at 11pt on A4 with the writer's own margins) purely so the two formats' numbers sit
in comparable units — it is explicitly marked as an ESTIMATE, not a measured page count.

**"Page" for PDF**: real, measured — ``fitz.open(path).page_count`` after generation, the
same page-flow logic ``corpus/pdf_builder.py`` uses in production.

No threshold: this is a report, not a gate. Exit code is always 0.
"""
from __future__ import annotations

import random
import sys
import time
import tracemalloc
from pathlib import Path

import fitz

from corpus.docx_builder import DocxBuilder
from corpus.groundtruth import PiiSpec, Recorder
from corpus.pdf_builder import PdfBuilder
from corpus.pii import email, rodne_cislo
from writer.docx_body import redact_docx_body
from writer.pdf_body import redact_pdf

_SCRATCH = Path(
    r"C:\Users\matus\AppData\Local\Temp\claude\C--Users-matus-A-MAIN-ws-013-legal-anonymizer-sk"
    r"\09b08adc-0a0a-4ba4-95ef-e1b2c5a198e8\scratchpad\perf_report"
)
_DOCX_PARAGRAPHS = 300      # "~300 docx paragraph-pages" per the task
_DOCX_PARAS_PER_PAGE_ESTIMATE = 40   # documented estimate, see module docstring
_PDF_TARGET_PAGES = 500    # "~500 pdf pages" per the task


def _content(idx: int) -> tuple[str, str]:
    rng = random.Random(idx)
    return rodne_cislo.generate(rng, valid=True), email.generate(rng)


def _build_large_docx(path: Path) -> int:
    rec = Recorder(path.name, "perf_fixture", 1)
    b = DocxBuilder(rec, random.Random(1))
    for i in range(_DOCX_PARAGRAPHS):
        rc, mail = _content(i)
        b.paragraph([
            f"Odsek {i}: Rodné číslo klienta je ", PiiSpec(rc, "RODNE_CISLO", valid_checksum=True),
            " a e-mail je ", PiiSpec(mail, "EMAIL"), ".",
        ])
    b.save(path)
    return _DOCX_PARAGRAPHS


def _build_large_pdf(path: Path) -> int:
    rec = Recorder(path.name, "perf_fixture", 2)
    b = PdfBuilder(rec)
    # Enough paragraphs to reach ~_PDF_TARGET_PAGES real pages, per PdfBuilder's own pagination
    # (measured empirically at generation time below rather than guessed).
    i = 0
    while i == 0 or b.page_no < _PDF_TARGET_PAGES:
        rc, mail = _content(i)
        b.paragraph([
            f"Odsek {i}: Rodné číslo klienta je ", PiiSpec(rc, "RODNE_CISLO", valid_checksum=True),
            " a e-mail je ", PiiSpec(mail, "EMAIL"), ".",
        ])
        i += 1
    b.save(path)
    return fitz.open(str(path)).page_count


def _measure(label: str, fn, *args) -> tuple[float, int, float]:
    """(wall_seconds, tracemalloc_peak_bytes, tracemalloc_peak_MiB)."""
    tracemalloc.start()
    t0 = time.perf_counter()
    fn(*args)
    elapsed = time.perf_counter() - t0
    _, peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    return elapsed, peak, peak / (1024 * 1024)


def run() -> int:
    _SCRATCH.mkdir(parents=True, exist_ok=True)
    docx_in = _SCRATCH / "perf_large.docx"
    docx_out = _SCRATCH / "perf_large_anon.docx"
    pdf_in = _SCRATCH / "perf_large.pdf"
    pdf_out = _SCRATCH / "perf_large_anon.pdf"

    print("perf report — generating large inputs (scratchpad only, not committed):", _SCRATCH)
    gen_t0 = time.perf_counter()
    n_paragraphs = _build_large_docx(docx_in)
    n_pages_pdf_target = _build_large_pdf(pdf_in)
    print(f"  generated: {docx_in.name} ({n_paragraphs} paragraphs, "
          f"{docx_in.stat().st_size / 1024:.0f} KiB), "
          f"{pdf_in.name} ({n_pages_pdf_target} pages, {pdf_in.stat().st_size / 1024:.0f} KiB) "
          f"in {time.perf_counter() - gen_t0:.1f}s")

    docx_elapsed, docx_peak_bytes, docx_peak_mib = _measure(
        "docx", redact_docx_body, str(docx_in), str(docx_out)
    )
    pdf_elapsed, pdf_peak_bytes, pdf_peak_mib = _measure(
        "pdf", redact_pdf, str(pdf_in), str(pdf_out)
    )

    docx_pages_est = n_paragraphs / _DOCX_PARAS_PER_PAGE_ESTIMATE
    pdf_pages = fitz.open(str(pdf_in)).page_count

    print()
    print("=== PERF (report only, no threshold) ===")
    print(f"  DOCX: {n_paragraphs} paragraphs (~{docx_pages_est:.1f} pages, ESTIMATE at "
          f"{_DOCX_PARAS_PER_PAGE_ESTIMATE} paragraphs/page — see module docstring)")
    print(f"        wall time    {docx_elapsed:.3f}s total, "
          f"{docx_elapsed / n_paragraphs * 1000:.2f} ms/paragraph, "
          f"{docx_elapsed / docx_pages_est:.3f} s/page (estimate)")
    print(f"        peak memory  {docx_peak_mib:.1f} MiB (tracemalloc — Python-heap only, "
          f"NOT process RSS; see module docstring)")
    print()
    print(f"  PDF:  {pdf_pages} pages (measured, real fitz page_count)")
    print(f"        wall time    {pdf_elapsed:.3f}s total, {pdf_elapsed / pdf_pages:.3f} s/page")
    print(f"        peak memory  {pdf_peak_mib:.1f} MiB (tracemalloc — Python-heap only, "
          f"NOT process RSS; see module docstring)")

    for p in _SCRATCH.glob("perf_large*"):
        p.unlink(missing_ok=True)
    print()
    print(f"scratch files removed from {_SCRATCH}")
    return 0


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    return run()


if __name__ == "__main__":
    sys.exit(main())
